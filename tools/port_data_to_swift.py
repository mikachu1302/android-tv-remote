#!/usr/bin/env python3
"""Regenerates the iOS app's data tables from the Android sources (single source of truth):
   ios/Sources/TVRemoteCore/GeneratedData.swift  <- Icons.kt, AppLogos.kt, Theme.kt (palettes), Prefs.kt (catalog)
Run after changing a palette, an icon path, a logo or the app catalog on the Android side."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "app/src/main/java/io/github/mikachu1302/tvremote"
out = root / "ios/Sources/TVRemoteCore/GeneratedData.swift"

def swift_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

icons = (src / "Icons.kt").read_text()
def map_block(name):
    m = re.search(r"private val %s = mapOf\((.*?)\n\)" % name, icons, re.S)
    return re.findall(r'"([^"]+)" to "([^"]+)"', m.group(1))
stroked, filled = map_block("STROKED"), map_block("FILLED")

logos_src = (src / "AppLogos.kt").read_text()
logos = re.findall(r'"([^"]+)" to AppLogo\(\s*"([^"]+)",\s*(Color\(0x[0-9A-Fa-f]+\)|null)', logos_src)

theme = (src / "Theme.kt").read_text()
pal = []
for var, body in re.findall(r"val (\w+) = Palette\((.*?)\n    \)", theme, re.S):
    def field(name):
        return re.search(name + r" = c\(0x(\w+)\)", body).group(1)
    pid, pname = re.search(r'"(\w+)", "([^"]+)"', body).groups()
    stripes = None
    m = re.search(r"stripes = listOf\((.*)\)\s*,?\s*$", body.strip(), re.S)
    if m:
        stripes = ", ".join("0x" + h for h in re.findall(r"c\(0x(\w+)\)", m.group(1)))
    pal.append((var, pid, pname, field("bg"), field("surface"), field("border"), field("text"), field("dim"),
                field("primary"), field("action"), field("soft"), field("warn"), stripes))
order = re.search(r"val all = listOf\(([^)]*)\)", theme).group(1).replace(" ", "").split(",")

prefs = (src / "Prefs.kt").read_text()
catalog, packages = [], []
for name, pkg, kind in re.findall(
        r'CatalogApp\("([^"]+)", "([^"]+)"(?:, ((?:dialLink|keyLink)\([^)]*\)|"[^"]+"))?\)', prefs):
    if not kind:
        link = "https://play.google.com/store/apps/details?id=" + pkg
    elif kind.startswith("dialLink"):
        link = "dial://" + re.search(r'"([^"]+)"', kind).group(1)
    elif kind.startswith("keyLink"):
        link = "key://" + re.search(r"\((\d+)\)", kind).group(1)
    else:
        link = kind.strip('"')
    catalog.append((name, link))
    packages.append((pkg, name))
generic = re.findall(r'"(\w+)"', re.search(r"GENERIC_PACKAGE_PARTS = setOf\((.*?)\)", prefs, re.S).group(1))

L = ["// GENERATED by tools/port_data_to_swift.py from the Android sources. Do not edit by hand.", "",
     "import Foundation", ""]
L.append("public enum GlyphData {")
L.append("    public static let stroked: [String: String] = [")
L += [f"        {swift_str(k)}: {swift_str(v)}," for k, v in stroked]
L.append("    ]")
L.append("    public static let filled: [String: String] = [")
L += [f"        {swift_str(k)}: {swift_str(v)}," for k, v in filled]
L.append("    ]\n}\n")

L.append("public struct AppLogo {\n    public let path: String\n    /// 0xRRGGBB, or nil when too dark to show on a dark screen.\n    public let brand: UInt32?\n}\n")
L.append("public let appLogos: [String: AppLogo] = [")
for name, path, color in logos:
    brand = "nil" if color == "null" else "0x" + re.search(r"0xFF([0-9A-Fa-f]{6})", color).group(1)
    L.append(f"    {swift_str(name)}: AppLogo(path: {swift_str(path)}, brand: {brand}),")
L.append("]\n")

L.append("public enum PaletteData {")
for var, pid, name, bg, surface, border, text, dim, primary, action, soft, warn, stripes in pal:
    st = "[" + stripes + "]" if stripes else "nil"
    L.append(f"    public static let {var.lower()} = Palette(id: {swift_str(pid)}, name: {swift_str(name)}, bg: 0x{bg}, surface: 0x{surface}, "
             f"border: 0x{border}, text: 0x{text}, dim: 0x{dim}, primary: 0x{primary}, action: 0x{action}, soft: 0x{soft}, warn: 0x{warn}, stripes: {st})")
L.append("    public static let all: [Palette] = [" + ", ".join(o.lower() for o in order) + "]")
L.append("}\n")

L.append("public let appCatalog: [AppShortcut] = [")
L += [f"    AppShortcut(name: {swift_str(n)}, link: {swift_str(l)})," for n, l in catalog]
L.append("]\n")
L.append("public let appPackages: [String: String] = [")
L += [f"    {swift_str(p)}: {swift_str(n)}," for p, n in packages]
L.append("]\n")
L.append("public let genericPackageParts: Set<String> = [" + ", ".join(swift_str(g) for g in generic) + "]\n")
out.write_text("\n".join(L))
print(f"{len(stroked)} stroked, {len(filled)} filled, {len(logos)} logos, {len(pal)} palettes, {len(catalog)} catalog apps, {len(generic)} generic parts")
