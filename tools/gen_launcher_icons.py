#!/usr/bin/env python3
"""Generates the launcher icons: one per palette in Theme.kt (TV in the "alive" colour, remote
in the action colour) and a Progress Pride one, plus the manifest aliases that switch between
them. Run from the repository root after changing a palette: python3 tools/gen_launcher_icons.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEME = ROOT / "app/src/main/java/io/github/mikachu1302/tvremote/Theme.kt"
RES = ROOT / "app/src/main/res"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"

PALETTE = re.compile(
    r'Palette\(\s*"(\w+)", "([^"]+)", bg = c\(0x(\w+)\), surface = c\(0x(\w+)\), border = c\(0x(\w+)\),\s*'
    r"text = c\(0x(\w+)\), dim = c\(0x(\w+)\), primary = c\(0x(\w+)\), action = c\(0x(\w+)\),\s*"
    r"soft = c\(0x(\w+)\), warn = c\(0x(\w+)\),",
    re.S,
)

# Geometry on the 108 x 108 canvas; the TV is open where the remote covers it.
TV = "M62,70 H26 A8,8 0 0 1 18,62 V34 A8,8 0 0 1 26,26 H78 A8,8 0 0 1 86,34 V50"
TV_FULL = "M26,26 H78 A8,8 0 0 1 86,34 V62 A8,8 0 0 1 78,70 H26 A8,8 0 0 1 18,62 V34 A8,8 0 0 1 26,26 Z"
STAND = "M30,80 L48,80"
REMOTE = "M70,50 H78 A8,8 0 0 1 86,58 V86 A8,8 0 0 1 78,94 H70 A8,8 0 0 1 62,86 V58 A8,8 0 0 1 70,50 Z"
DOT1 = "M71.2,59 a2.8,2.8 0 1,0 5.6,0 a2.8,2.8 0 1,0 -5.6,0 Z"
RING = "M68.5,72 a5.5,5.5 0 1,0 11,0 a5.5,5.5 0 1,0 -11,0 Z"
DOT3 = "M72,84 a2,2 0 1,0 4,0 a2,2 0 1,0 -4,0 Z"

HEAD = """<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- generated by tools/gen_launcher_icons.py -->
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="0.88"
        android:scaleY="0.88"
        android:translateY="-3">
"""
TAIL = "    </group>\n</vector>\n"


def stroke(path, color, width=4.5):
    return (
        f'        <path android:pathData="{path}" android:strokeColor="{color}" android:strokeWidth="{width}" '
        'android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
    )


def fill(path, color):
    return f'        <path android:pathData="{path}" android:fillColor="{color}" />\n'


def remote_art(tv, remote, dot1, ring, dot3):
    return stroke(TV, tv) + stroke(STAND, tv) + stroke(REMOTE, remote) + fill(DOT1, dot1) + stroke(RING, ring, 3.5) + fill(DOT3, dot3)


def palette_icon(p):
    prim, act = "#" + p["primary"], "#" + p["action"]
    return HEAD + remote_art(prim, act, act, act, act) + TAIL


PRIDE_STRIPES = ["#E40303", "#FF8C00", "#FFED00", "#008026", "#004DFF", "#750787"]
# The arrow's sides run at 45 degrees (tip as far from the hoist as half the flag's height),
# five bands nested evenly: each one steps in by the same amount vertically and horizontally.
PRIDE_CHEVRON = [  # outermost first
    ("#000000", "M18,26 L40,48 L18,70 Z"),
    ("#613915", "M18,30.4 L35.6,48 L18,65.6 Z"),
    ("#74D7EE", "M18,34.8 L31.2,48 L18,61.2 Z"),
    ("#FFAFC8", "M18,39.2 L26.8,48 L18,56.8 Z"),
    ("#FFFFFF", "M18,43.6 L22.4,48 L18,52.4 Z"),
]


def pride_icon():
    out = HEAD
    out += f'        <group>\n            <clip-path android:pathData="{TV_FULL}" />\n'
    h = 44 / 6
    for i, color in enumerate(PRIDE_STRIPES):
        y0, y1 = 26 + i * h, 26 + (i + 1) * h + 0.2
        out += f'            <path android:pathData="M18,{y0:.2f} H86 V{y1:.2f} H18 Z" android:fillColor="{color}" />\n'
    for color, path in PRIDE_CHEVRON:
        out += f'            <path android:pathData="{path}" android:fillColor="{color}" />\n'
    out += "        </group>\n"
    out += stroke(TV_FULL, "#FFFFFF") + stroke(STAND, "#FFFFFF") + stroke(REMOTE, "#FFFFFF")
    out += fill(DOT1, "#FFAFC8") + stroke(RING, "#74D7EE", 3.5) + fill(DOT3, "#FFED00")
    return out + TAIL


def mono_icon():
    return HEAD + remote_art("#FFFFFF", "#FFFFFF", "#FFFFFF", "#FFFFFF", "#FFFFFF") + TAIL


def adaptive(fg, bg):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="@color/{bg}" />\n'
        f'    <foreground android:drawable="@drawable/{fg}" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )


def main():
    palettes = [
        dict(zip(("id", "name", "bg", "surface", "border", "text", "dim", "primary", "action", "soft", "warn"), m))
        for m in PALETTE.findall(THEME.read_text())
    ]
    assert palettes, "no palettes found in Theme.kt"
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)

    colors = ['<resources>', '    <!-- generated by tools/gen_launcher_icons.py -->']
    aliases = []
    ids = []
    for p in palettes:
        (RES / f"drawable/ic_launcher_fg_{p['id']}.xml").write_text(palette_icon(p))
        (RES / f"mipmap-anydpi/ic_launcher_{p['id']}.xml").write_text(adaptive(f"ic_launcher_fg_{p['id']}", f"ic_launcher_bg_{p['id']}"))
        colors.append(f'    <color name="ic_launcher_bg_{p["id"]}">#{p["bg"]}</color>')
        ids.append(p["id"])
    (RES / "drawable/ic_launcher_fg_pride.xml").write_text(pride_icon())
    (RES / "mipmap-anydpi/ic_launcher_pride.xml").write_text(adaptive("ic_launcher_fg_pride", "ic_launcher_bg_pride"))
    colors.append('    <color name="ic_launcher_bg_pride">#0E0E14</color>')
    colors.append("</resources>")
    ids.append("pride")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(mono_icon())
    (RES / "values/launcher_colors.xml").write_text("\n".join(colors) + "\n")

    for i in ids:
        name = "Launcher" + i.capitalize()
        enabled = "true" if i == "neon" else "false"
        aliases.append(
            f'        <activity-alias\n            android:name=".{name}"\n            android:enabled="{enabled}"\n'
            f'            android:exported="true"\n            android:icon="@mipmap/ic_launcher_{i}"\n'
            '            android:label="@string/app_name"\n            android:targetActivity=".MainActivity">\n'
            '            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n'
            '                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n'
            "        </activity-alias>"
        )
    begin, end = "<!-- BEGIN launcher aliases (tools/gen_launcher_icons.py) -->", "<!-- END launcher aliases -->"
    block = f"        {begin}\n" + "\n".join(aliases) + f"\n        {end}\n"
    m = MANIFEST.read_text()
    if begin in m:
        m = re.sub(re.escape("        " + begin) + r".*?" + re.escape(end) + r"\n", lambda _: block, m, flags=re.S)
    else:
        m = m.replace("    </application>", block + "    </application>")
    # The activity itself is no longer a launcher entry: the aliases are.
    m = re.sub(
        r'\n            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n'
        r'                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>(?=\n        </activity>\n        <!-- BEGIN)',
        "", m,
    )
    m = re.sub(r'android:icon="@mipmap/ic_launcher"', 'android:icon="@mipmap/ic_launcher_neon"', m)
    MANIFEST.write_text(m)
    print("generated icons for:", ", ".join(ids))


main()
