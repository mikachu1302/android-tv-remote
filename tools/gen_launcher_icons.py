#!/usr/bin/env python3
"""Generates the launcher icons: one per palette in Theme.kt (TV in the "alive" colour, remote
in the action colour) and five Progress Pride ones, plus the manifest aliases that switch between
them. Run from the repository root after changing a palette: python3 tools/gen_launcher_icons.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEME = ROOT / "app/src/main/java/io/github/mikachu1302/tvremote/Theme.kt"
RES = ROOT / "app/src/main/res"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"

PALETTE = re.compile(
    r'Palette\(\s*"(\w+)", "([^"]+)", bg = c\(0x(\w+)\), surface = c\(0x(\w+)\), border = c\(0x(\w+)\),\s*'
    r"text = c\(0x(\w+)\), dim = c\(0x(\w+)\), primary = c\(0x(\w+)\), action = c\(0x(\w+)\),\s*"
    r"soft = c\(0x(\w+)\), warn = c\(0x(\w+)\),",
    re.S,
)

# Geometry on the 108 x 108 canvas; the TV is open where the remote covers it. The group around the
# art scales it to about 52 units and centres its bounding box (centre 52, 60). Phone launchers draw the
# icon through a mask and show only the central ~66 units (Samsung's home screen included), so anything
# larger gets its corners cut off.
TV = "M62,70 H26 A8,8 0 0 1 18,62 V34 A8,8 0 0 1 26,26 H78 A8,8 0 0 1 86,34 V50"
STAND = "M30,80 L48,80"
REMOTE = "M70,50 H78 A8,8 0 0 1 86,58 V86 A8,8 0 0 1 78,94 H70 A8,8 0 0 1 62,86 V58 A8,8 0 0 1 70,50 Z"
BEZEL = "M25,23 H79 A10,10 0 0 1 89,33 V63 A10,10 0 0 1 79,73 H25 A10,10 0 0 1 15,63 V33 A10,10 0 0 1 25,23 Z"
RAINBOW_BEZEL = "M25.5,24.5 H78.5 A9,9 0 0 1 87.5,33.5 V62.5 A9,9 0 0 1 78.5,71.5 H25.5 A9,9 0 0 1 16.5,62.5 V33.5 A9,9 0 0 1 25.5,24.5 Z"
RAINBOW_SCREEN = "M26,29 H78 A5,5 0 0 1 83,34 V62 A5,5 0 0 1 78,67 H26 A5,5 0 0 1 21,62 V34 A5,5 0 0 1 26,29 Z"
PLAY = "M45,38 L45,58 L63,48 Z"
BIG_REMOTE = "M66,46 H76 A9,9 0 0 1 85,55 V84 A9,9 0 0 1 76,93 H66 A9,9 0 0 1 57,84 V55 A9,9 0 0 1 66,46 Z"
SCREEN_CLIP = "M7,0 H61 A7,7 0 0 1 68,7 V37 A7,7 0 0 1 61,44 H7 A7,7 0 0 1 0,37 V7 A7,7 0 0 1 7,0 Z"

STRIPES = ["#E40303", "#FF8C00", "#FFED00", "#008026", "#004DFF", "#750787"]
# The arrow's sides run at 45 degrees (tip as far from the hoist as half the flag's height), five bands
# nested evenly, outermost first. Coordinates are in the flag's own 68 x 44 space.
CHEVRON = [
    ("#000000", "M0,0 L22,22 L0,44 Z"),
    ("#613915", "M0,4.4 L17.6,22 L0,39.6 Z"),
    ("#74D7EE", "M0,8.8 L13.2,22 L0,35.2 Z"),
    ("#FFAFC8", "M0,13.2 L8.8,22 L0,30.8 Z"),
    ("#FFFFFF", "M0,17.6 L4.4,22 L0,26.4 Z"),
]

HEAD = """<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- generated by tools/gen_launcher_icons.py -->
"""
TAIL = "</vector>\n"
STD = dict(s=0.72, tx=1.44, ty=-4.32)


def fmt(v):
    return f"{v:g}"


def group(art, s=0.72, tx=0.0, ty=0.0):
    return (
        f'    <group android:pivotX="54" android:pivotY="54" android:scaleX="{fmt(s)}" android:scaleY="{fmt(s)}" '
        f'android:translateX="{fmt(tx)}" android:translateY="{fmt(ty)}">\n{art}    </group>\n'
    )


def circle(cx, cy, r):
    return f"M{fmt(cx - r)},{fmt(cy)} a{fmt(r)},{fmt(r)} 0 1,0 {fmt(2 * r)},0 a{fmt(r)},{fmt(r)} 0 1,0 -{fmt(2 * r)},0 Z"


def stroke(path, color, width=4.5, fill_color=None):
    f = f' android:fillColor="{fill_color}"' if fill_color else ""
    return (
        f'        <path android:pathData="{path}"{f} android:strokeColor="{color}" android:strokeWidth="{fmt(width)}" '
        'android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
    )


def fill(path, color):
    return f'        <path android:pathData="{path}" android:fillColor="{color}" />\n'


def remote_art(tv, remote, dot1, ring, dot3):
    return (
        stroke(TV, tv) + stroke(STAND, tv) + stroke(REMOTE, remote)
        + fill(circle(74, 59, 2.8), dot1) + stroke(circle(74, 72, 5.5), ring, 3.5) + fill(circle(74, 84, 2), dot3)
    )


def palette_icon(p):
    prim, act = "#" + p["primary"], "#" + p["action"]
    return HEAD + group(remote_art(prim, act, act, act, act), **STD) + TAIL


def flag(x, y, scale):
    out = (
        f'        <group android:translateX="{fmt(x)}" android:translateY="{fmt(y)}" '
        f'android:scaleX="{fmt(scale)}" android:scaleY="{fmt(scale)}">\n'
        f'            <clip-path android:pathData="{SCREEN_CLIP}" />\n'
    )
    h = 44 / 6
    for i, color in enumerate(STRIPES):
        y0 = i * h
        y1 = min(44.0, y0 + h + 0.3)
        out += f'            <path android:pathData="M0,{y0:.2f} H68 V{y1:.2f} H0 Z" android:fillColor="{color}" />\n'
    for color, path in CHEVRON:
        out += f'            <path android:pathData="{path}" android:fillColor="{color}" />\n'
    return out + "        </group>\n"


def pride_dots(dot1="#E40303", ring="#004DFF", dot3="#FF8C00"):
    return fill(circle(74, 59, 2.8), dot1) + stroke(circle(74, 72, 5.5), ring, 3.5) + fill(circle(74, 84, 2.2), dot3)


def rainbow_stroke(path, fill_color, width):
    stops = "".join(
        f'                    <item android:offset="{i / 5:g}" android:color="{c}" />\n' for i, c in enumerate(STRIPES)
    )
    return (
        f'        <path android:pathData="{path}" android:fillColor="{fill_color}" android:strokeWidth="{fmt(width)}" '
        'android:strokeLineJoin="round">\n'
        '            <aapt:attr name="android:strokeColor">\n'
        '                <gradient android:startX="15" android:startY="0" android:endX="89" android:endY="0" android:type="linear">\n'
        f"{stops}"
        "                </gradient>\n"
        "            </aapt:attr>\n"
        "        </path>\n"
    )


def remote_pride(body, outline, outline_width):
    return stroke(REMOTE, outline, outline_width, fill_color=body) + pride_dots()


# id -> (foreground vector, background): a "#rrggbb" colour or a drawable name for a gradient.
def pride_variants():
    bezel = (
        fill(BEZEL, "#2E2D3D") + flag(18, 26, 1) + stroke(STAND, "#55556A", 5)
        + remote_pride("#F4F4F8", "#17161F", 3.5)
    )
    light = (
        fill(BEZEL, "#2B2A3A") + flag(18, 26, 1) + stroke(STAND, "#2B2A3A", 5)
        + remote_pride("#FFFFFF", "#2B2A3A", 4)
    )
    rainbow = (
        rainbow_stroke(RAINBOW_BEZEL, "#1F1E2B", 4) + fill(RAINBOW_SCREEN, "#0B0A12") + fill(PLAY, "#FFFFFF")
        + stroke(STAND, "#55556A", 5) + remote_pride("#F4F4F8", "#14131C", 3.5)
    )
    night = (
        fill(BEZEL, "#1B1A2A") + flag(18, 26, 1) + stroke(STAND, "#9A9AC8", 5)
        + remote_pride("#F4F4F8", "#1B1A2A", 3.5)
    )
    big = (
        flag(14, 20, 76 / 68)
        + stroke(BIG_REMOTE, "#17161F", 4, fill_color="#F4F4F8")
        + fill(circle(71, 56, 3), "#E40303") + stroke(circle(71, 69, 6), "#004DFF", 3.6) + fill(circle(71, 82, 2.4), "#FF8C00")
    )
    return {
        "pride_bezel": (HEAD + group(bezel, **STD) + TAIL, "#17161F"),
        "pride_light": (HEAD + group(light, **STD) + TAIL, "#F3F2F8"),
        "pride_rainbow": (HEAD + group(rainbow, **STD) + TAIL, "#14131C"),
        "pride_night": (HEAD + group(night, **STD) + TAIL, "ic_launcher_bg_pride_night"),
        "pride_big": (HEAD + group(big, s=0.74, ty=-2) + TAIL, "#17161F"),
    }


NIGHT_BG = """<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/gen_launcher_icons.py -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:endColor="#0F2A5C" android:startColor="#3A1F6B" android:type="linear" />
</shape>
"""


def mono_icon():
    return HEAD + group(remote_art("#FFFFFF", "#FFFFFF", "#FFFFFF", "#FFFFFF", "#FFFFFF"), **STD) + TAIL


def adaptive(fg, bg):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="{bg}" />\n'
        f'    <foreground android:drawable="@drawable/{fg}" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )


def camel(icon_id):
    return "".join(part.capitalize() for part in icon_id.split("_"))


def main():
    palettes = [
        dict(zip(("id", "name", "bg", "surface", "border", "text", "dim", "primary", "action", "soft", "warn"), m))
        for m in PALETTE.findall(THEME.read_text())
    ]
    assert palettes, "no palettes found in Theme.kt"
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)

    # Start clean: icons that no longer exist must not linger.
    for pattern, folder in (("ic_launcher_fg_*.xml", "drawable"), ("ic_launcher_bg_*.xml", "drawable"), ("ic_launcher_*.xml", "mipmap-anydpi")):
        for f in (RES / folder).glob(pattern):
            f.unlink()

    colors = ["<resources>", "    <!-- generated by tools/gen_launcher_icons.py -->"]
    ids = []
    for p in palettes:
        i = p["id"]
        (RES / f"drawable/ic_launcher_fg_{i}.xml").write_text(palette_icon(p))
        (RES / f"mipmap-anydpi/ic_launcher_{i}.xml").write_text(adaptive(f"ic_launcher_fg_{i}", f"@color/ic_launcher_bg_{i}"))
        colors.append(f'    <color name="ic_launcher_bg_{i}">#{p["bg"]}</color>')
        ids.append(i)

    for i, (fg_xml, bg) in pride_variants().items():
        (RES / f"drawable/ic_launcher_fg_{i}.xml").write_text(fg_xml)
        if bg.startswith("#"):
            colors.append(f'    <color name="ic_launcher_bg_{i}">{bg}</color>')
            bg_ref = f"@color/ic_launcher_bg_{i}"
        else:
            (RES / f"drawable/{bg}.xml").write_text(NIGHT_BG)
            bg_ref = f"@drawable/{bg}"
        (RES / f"mipmap-anydpi/ic_launcher_{i}.xml").write_text(adaptive(f"ic_launcher_fg_{i}", bg_ref))
        ids.append(i)

    colors.append("</resources>")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(mono_icon())
    (RES / "values/launcher_colors.xml").write_text("\n".join(colors) + "\n")

    aliases = []
    for i in ids:
        name = "Launcher" + camel(i)
        enabled = "true" if i == "neon" else "false"
        aliases.append(
            f'        <activity-alias\n            android:name=".{name}"\n            android:enabled="{enabled}"\n'
            f'            android:exported="true"\n            android:icon="@mipmap/ic_launcher_{i}"\n'
            '            android:label="@string/app_name"\n            android:targetActivity=".MainActivity">\n'
            '            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n'
            '                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n'
            "        </activity-alias>"
        )
    begin, end = "<!-- BEGIN launcher aliases (tools/gen_launcher_icons.py) -->", "<!-- END launcher aliases -->"
    block = f"        {begin}\n" + "\n".join(aliases) + f"\n        {end}\n"
    m = MANIFEST.read_text()
    if begin in m:
        m = re.sub(re.escape("        " + begin) + r".*?" + re.escape(end) + r"\n", lambda _: block, m, flags=re.S)
    else:
        m = m.replace("    </application>", block + "    </application>")
    MANIFEST.write_text(m)
    print("generated icons for:", ", ".join(ids))


if __name__ == "__main__":
    main()
